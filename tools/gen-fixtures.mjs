#!/usr/bin/env node
// fixtures/derive/*.json -> firmware/test/fixtures.g.h   (§11.1)
//
// Exists so the host test binary needs no JSON parser and no ESP-IDF: plain
// `cc` over three .c files. Like gen-config, this is transliteration only —
// every "HH:MM" stays a string and is resolved by wfh_at_time() inside the
// test, so the fixtures cannot accidentally test a second implementation of
// local-time maths. The one exception is `expect.nextEpoch`, whose integers
// are hand-computed in the fixture precisely so the DST cases are anchored
// to something the code under test did not produce.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'fixtures/derive');
const out = resolve(root, 'firmware/test/fixtures.g.h');

const str = (s) => (s === undefined || s === null ? 'NULL' : JSON.stringify(String(s)));
const FLOWS = { tap: 'FLOW_TAP', stretch: 'FLOW_STRETCH' };

const cadence = (c) =>
  c.kind === 'interval'
    ? `{ .kind = CADENCE_INTERVAL, .every_min = ${c.everyMin} }`
    : `{ .kind = CADENCE_FIXED, .n_times = ${c.times.length}, .times = { ${c.times.map(str).join(', ')} } }`;

const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const blocks = [];
const rows = [];

for (const file of files) {
  const fx = JSON.parse(readFileSync(resolve(dir, file), 'utf8'));
  const tag = fx.name.replace(/[^a-z0-9]/gi, '_');
  const e = fx.expect ?? {};
  const lines = [];

  const arr = (suffix, items, type, render) => {
    if (!items || items.length === 0) return { ptr: 'NULL', n: 0 };
    lines.push(`static const ${type} ${tag}_${suffix}[] = {\n${items.map(render).join('\n')}\n};`);
    return { ptr: `${tag}_${suffix}`, n: items.length };
  };

  const acts = arr('actions', fx.actions, 'action_def_t', (a) =>
    `    { .id = ${str(a.id)}, .name = ${str(a.name)}, .target = ${a.target}, ` +
    `.priority = ${a.priority}, .flow = ${FLOWS[a.flow]}, .cadence = ${cadence(a.cadence)} },`);

  const evs = arr('events', fx.events, 'fx_event_t', (v) =>
    `    { ${str(v.action)}, ${str(v.kind)}, ${str(v.ts)}, ${str(v.slot)} },`);

  const kv = (suffix, obj) =>
    arr(suffix, Object.entries(obj ?? {}), 'fx_kv_t', ([k, v]) => `    { ${str(k)}, ${str(v)} },`);
  const ki = (suffix, obj) =>
    arr(suffix, Object.entries(obj ?? {}), 'fx_ki_t', ([k, v]) => `    { ${str(k)}, ${v} },`);
  const ke = (suffix, obj) =>
    arr(suffix, Object.entries(obj ?? {}), 'fx_ke_t', ([k, v]) => `    { ${str(k)}, ${v}LL },`);
  const names = (suffix, list) =>
    arr(suffix, list, 'char *const', (n) => `    ${str(n)},`);

  const snoozes = kv('snoozes', fx.snoozedUntil);
  const counts = ki('counts', e.counts);
  const skipped = ki('skipped', e.skipped);
  const missed = ki('missed', e.missed);
  const next = kv('next', e.next);
  const nextEpoch = ke('next_epoch', e.nextEpoch);
  const nextNone = names('next_none', e.nextNone);
  const due = names('due', e.due);

  blocks.push(lines.join('\n\n'));
  rows.push(`    { .name = ${str(fx.name)}, .why = ${str(fx.why)}, .tz = ${str(fx.tz)},
      .date = ${str(fx.date)}, .now = ${str(fx.now)}, .mode = ${str(fx.mode ?? 'once')},
      .work_start = ${str(fx.workStart ?? null)}, .work_end = ${str(fx.workEnd ?? null)},
      .grace_min = ${fx.graceMin ?? -1},
      .actions = ${acts.ptr}, .n_actions = ${acts.n},
      .events = ${evs.ptr}, .n_events = ${evs.n},
      .snoozes = ${snoozes.ptr}, .n_snoozes = ${snoozes.n},
      .counts = ${counts.ptr}, .n_counts = ${counts.n},
      .skipped = ${skipped.ptr}, .n_skipped = ${skipped.n},
      .missed = ${missed.ptr}, .n_missed = ${missed.n},
      .next = ${next.ptr}, .n_next = ${next.n},
      .next_epoch = ${nextEpoch.ptr}, .n_next_epoch = ${nextEpoch.n},
      .next_none = ${nextNone.ptr}, .n_next_none = ${nextNone.n},
      .due = ${due.ptr}, .n_due = ${due.n} },`);
}

writeFileSync(out, `// GENERATED by tools/gen-fixtures.mjs from fixtures/derive/*.json — do not edit.
#pragma once

#include "wfh_types.h"

typedef struct { const char *action, *kind, *ts, *slot; } fx_event_t;
typedef struct { const char *key; const char *value; } fx_kv_t;
typedef struct { const char *key; int value; } fx_ki_t;
typedef struct { const char *key; long long value; } fx_ke_t;

typedef struct {
    const char *name, *why, *tz, *date, *now, *mode, *work_start, *work_end;
    int grace_min;                                  // -1 = use config default
    const action_def_t *actions;  int n_actions;    // NULL = shipping config
    const fx_event_t   *events;   int n_events;
    const fx_kv_t      *snoozes;  int n_snoozes;
    const fx_ki_t      *counts;   int n_counts;     // exhaustive
    const fx_ki_t      *skipped;  int n_skipped;    // exhaustive
    const fx_ki_t      *missed;   int n_missed;     // exhaustive
    const fx_kv_t      *next;     int n_next;       // partial
    const fx_ke_t      *next_epoch; int n_next_epoch;
    const char *const  *next_none;  int n_next_none;
    const char *const  *due;      int n_due;        // exact, ordered
} fixture_t;

${blocks.join('\n\n')}

static const fixture_t FIXTURES[] = {
${rows.join('\n\n')}
};

#define FIXTURE_COUNT ${files.length}
`);

console.log(`gen-fixtures: ${files.length} fixtures -> firmware/test/fixtures.g.h`);
